#!/usr/bin/env python3
"""Translate shell transparency into a sourced Mango layer-rule fragment."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib


def rule_text(enabled, alpha, alpha_supported=False):
    threshold = max(0.0, min(1.0, alpha - 0.03))
    rule = f"layer_rule=layer_name:^caelestia-drawers$,no_blur:{0 if enabled else 1}"
    if alpha_supported:
        rule += f",blur_ignore_alpha:{threshold:.4f}"
    return "# Generated by Caelestia; do not edit.\n" + rule + "\n"


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == content:
        return False
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as file:
        file.write(content)
        temporary = Path(file.name)
    temporary.replace(path)
    return True


def supports_alpha():
    executable = shutil.which("mango")
    return bool(executable and b"blur_ignore_alpha" in Path(executable).read_bytes())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--enabled", type=int, choices=(0, 1), required=True)
    parser.add_argument("--alpha", type=float, required=True)
    parser.add_argument("--setup", action="store_true", help="Source the fragment and enable Mango layer blur")
    args = parser.parse_args()
    home = Path.home()
    config_dir = Path(os.environ.get("XDG_CONFIG_HOME", home / ".config")) / "mango"
    config = Path(os.environ["CAELESTIA_MANGO_CONFIG"]).expanduser() if os.environ.get("CAELESTIA_MANGO_CONFIG") else next(
        (p for p in [config_dir / "config.conf", config_dir / "config.toml"] if p.exists()), config_dir / "config.conf")
    state = Path(os.environ.get("XDG_STATE_HOME", home / ".local/state")) / "caelestia" / "mango-blur.conf"
    alpha_supported = supports_alpha()
    # Runtime calls do not edit the user's compositor configuration.
    if args.setup and config.is_symlink():
        raise RuntimeError("Config is managed through a symlink; add blur settings and the source fragment declaratively")
    if args.setup and config.suffix == ".toml":
        raise RuntimeError("TOML setup is declarative: add blur=1, blur_layer=1 and the state fragment to [global].source")
    configured = False
    if config.exists():
        if config.suffix == ".toml":
            sources = tomllib.loads(config.read_text()).get("global", {}).get("source", [])
            if isinstance(sources, str): sources = [sources]
            configured = any(Path(os.path.expandvars(source)).expanduser() == state for source in sources)
        else:
            configured = f"source={state}" in config.read_text()
    if not args.setup and not configured:
        print(json.dumps({"changed": False, "configured": False}))
        return
    changed = atomic_write(state, rule_text(bool(args.enabled), args.alpha, alpha_supported))
    if args.setup:
        original = config.read_text() if config.exists() else "source=/etc/mango/config.conf\n"
        # Replace only the exact legacy rule documented by this fork.
        start = "# BEGIN CAELESTIA BLUR"
        end = "# END CAELESTIA BLUR"
        lines = []
        inside = False
        for line in original.splitlines():
            if line == start:
                inside = True
            elif line == end:
                inside = False
            elif not inside and line.strip() not in ("layer_rule=layer_name:caelestia.*,no_blur:1", f"source={state}"):
                lines.append(line)
        while lines and not lines[-1].strip():
            lines.pop()
        lines += ["", start, "blur=1", "blur_layer=1", f"source={state}", end]
        updated = "\n".join(lines) + "\n"
        if updated != original:
            if config.exists():
                backup = config.with_name("config.conf.before-caelestia-blur")
                if not backup.exists():
                    backup.write_text(original)
            atomic_write(config, updated)
            changed = True
    if changed:
        result = subprocess.run(["mmsg", "dispatch", "reload_config"], capture_output=True, text=True, timeout=10)
        payload = json.loads(result.stdout or "{}")
        if result.returncode or not payload.get("success"):
            raise RuntimeError(payload.get("error") or result.stderr or "Mango reload failed")
    print(json.dumps({"changed": changed, "configured": True, "alphaSupported": alpha_supported}))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"Mango blur sync failed: {error}", file=sys.stderr)
        sys.exit(1)
